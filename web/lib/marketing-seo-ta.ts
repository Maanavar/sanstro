export function trimTamilDescription(text: string, max = 160): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max);
  const at = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf(", "), cut.lastIndexOf("; "));
  return at > max * 0.5 ? cut.slice(0, at + 1).replace(/[,;]$/, ".") : cut.replace(/\s\S*$/, "") + "…";
}

function guideTamilCopy(section: string, slug: string): MetaCopy | null {
  const kind = GUIDE_KIND[section];
  const detail = kind ? getGuideDetail(kind, slug) : undefined;
  if (!detail) return null;
  return {
    title: `${detail.title.ta}${GUIDE_TITLE_SUFFIX_TA[section] ?? ""}`,
    description: trimTamilDescription(detail.lead.ta),
  };
}

/** Tamil search copy for `path`, or null when the page has none (and so has no twin). */
export function tamilCopyFor(path: string): MetaCopy | null {
  const listed = PAGE_SEO_TA[path];
  if (listed) return listed;
  const guide = path.match(/^\/(dosham|yogam|pariharam|temples)\/([^/]+)$/);
  return guide ? guideTamilCopy(guide[1]!, guide[2]!) : null;
}
