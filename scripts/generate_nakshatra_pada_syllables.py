"""Emit the naming syllables (நட்சத்திர எழுத்துக்கள்) the Jadhagam prints (AAU-04).

Why a generator
---------------
The Jadhagam sheet hand-typed the four starting syllables per star. It
differed from the app's naming canon (`app/data/nakshatra_pada_akshara.py`) in
59 of 108 cells, 14 of them in the consonant: an Aswini pada-1 baby was told
"அ", which is Karthigai's letter. One fact, two tables; the canon wins, and
the sheet now renders it.

Display policy (AAU-04, decided 2026-10-29 under the owner's delegation):
Tamil-first. The sheet prints the canon's Tamil form; the canonical Sanskrit
syllable stays in the canon, where name filtering reads it (two padas that
collapse to one Tamil letter are still told apart there).

The canon is a draft until the astrologer signs it, so the file carries the
verified-row count and the sheet says "unverified" while it is below 108.
Re-run after any change to the canon::

    $env:PYTHONUTF8 = "1"
    python scripts/generate_nakshatra_pada_syllables.py

``tests/test_nakshatra_pada_syllables_ts.py`` fails if the committed file is stale.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from app.data.nakshatra_pada_akshara import (  # noqa: E402
    CANON_VERSION,
    PADA_AKSHARA_TABLE,
    verified_row_count,
)

OUTPUT = REPO / "web" / "lib" / "generated" / "nakshatra-pada-syllables.ts"


def build() -> dict[str, object]:
    syllables: dict[int, list[str]] = {}
    for row in sorted(PADA_AKSHARA_TABLE, key=lambda r: r.key):
        syllables.setdefault(row.nakshatra_id, []).append(row.akshara_tamil)
    return {
        "canonVersion": CANON_VERSION,
        "verifiedRows": verified_row_count(),
        "totalRows": len(PADA_AKSHARA_TABLE),
        "syllables": syllables,
    }


def render(data: dict[str, object]) -> str:
    rows = "\n".join(
        f"  {star}: {json.dumps(pada, ensure_ascii=False)},"
        for star, pada in data["syllables"].items()  # type: ignore[union-attr]
    )
    return (
        "// GENERATED by scripts/generate_nakshatra_pada_syllables.py from\n"
        "// app/data/nakshatra_pada_akshara.py. Do not edit by hand (AAU-04).\n"
        f"export const PADA_SYLLABLE_CANON_VERSION = {json.dumps(data['canonVersion'])};\n"
        f"export const PADA_SYLLABLE_VERIFIED_ROWS = {data['verifiedRows']};\n"
        f"export const PADA_SYLLABLE_TOTAL_ROWS = {data['totalRows']};\n"
        "\n"
        "/** Tamil starting syllable per pada (1..4), keyed by nakshatra 1..27. */\n"
        "export const PADA_SYLLABLES_TA: Record<number, readonly [string, string, string, string]> = {\n"
        f"{rows}\n"
        "};\n"
    )


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(build()), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
