// Condition-4 worklist for the nakshatra visual pages: for every dasa string, compare
// the English and Tamil sentence counts and flag the Tamil that is shorter. A shortfall
// is usually a dropped sentence (the 2026-10-21 review found them to be mostly cautions).
// It cannot see a sentence that is present but means something else.
// Usage: node scripts/dasa_prose_parity_worklist.mjs > docs/DASA_PROSE_PARITY_WORKLIST_<date>.md
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url)).replace(/\\/g, "/").replace(/\/$/, "");
const DIR = `${ROOT}/web/app/(marketing)/natchathiram`;
const slugs = readdirSync(DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();

// Sentence ends: . ! ? followed by space or end. Abbreviations do not occur in this prose.
const sentences = (t) => t.split(/(?<=[.!?])\s+/).map((x) => x.trim()).filter(Boolean);

const rows = [];
for (const slug of slugs) {
  const src = readFileSync(`${DIR}/${slug}/visual/page.tsx`, "utf8").split(/\r?\n/);
  const find = (re, from = 0) => { for (let i = from; i < src.length; i++) if (re.test(src[i])) return i; return -1; };
  const enS = find(/^\s*dashaTimeline:/), enE = find(/^\s*spirituality:/, enS);
  const dtS = find(/^\s*dashaDetails:/, enE), taE = find(/^\s*spirituality:/, dtS);
  const planets = [];
  for (let i = enS; i < enE; i++) { const m = /planet: "(\w+)"/.exec(src[i]); if (m) planets.push(m[1]); }
  const fields = (a, b) => {
    const out = []; let d = -1;
    for (let i = a; i < b; i++) {
      const m = /^\s+(expect|navigate|focus): (".*"),\s*$/.exec(src[i]);
      if (!m) continue;
      if (m[1] === "expect") d++;
      out.push({ dasa: d, field: m[1], text: JSON.parse(m[2]) });
    }
    return out;
  };
  const en = fields(enS, enE), ta = fields(dtS, taE);
  // A dasa missing from the Tamil map yields no row below (the loop is over English), which is how
  // 21 pages lost their eighth Tamil dasa unnoticed. Refuse to produce a list that cannot see that.
  if (en.length !== ta.length || en.length !== planets.length * 3) {
    console.error(`${slug}: ${planets.length} dasas, ${en.length} English fields, ${ta.length} Tamil fields — expected ${planets.length * 3} each`);
    process.exit(1);
  }
  for (const e of en) {
    const t = ta.find((x) => x.dasa === e.dasa && x.field === e.field);
    const ne = sentences(e.text).length, nt = t ? sentences(t.text).length : 0;
    if (nt < ne) rows.push({ slug, planet: planets[e.dasa], field: e.field, ne, nt, last: sentences(e.text).at(-1) });
  }
}

rows.sort((a, b) => (b.ne - b.nt) - (a.ne - a.nt) || a.slug.localeCompare(b.slug));
console.log(`# Dasa prose — EN/TA sentence-count worklist`);
console.log();
console.log(`Generated by \`scripts/dasa_prose_parity_worklist.mjs\`. One row per dasa string whose Tamil has fewer sentences than its English twin (${rows.length} rows across ${new Set(rows.map((r) => r.slug)).size} pages), largest shortfall first. "Last English sentence" is the one most often missing.`);
console.log();
console.log(`**What this cannot see:** a Tamil sentence that is present but says something else, or one sentence that merges two English ones (shows as a shortfall of one that may be fine). It is a triage list for condition 4, not a verdict.`);
console.log();
console.log(`| Page | Dasa | Field | EN | TA | Last English sentence |`);
console.log(`|---|---|---|---|---|---|`);
for (const r of rows) console.log(`| ${r.slug} | ${r.planet} | ${r.field} | ${r.ne} | ${r.nt} | ${r.last.replace(/\|/g, "\\|")} |`);
